static s32 kt_ground_ready(u32 a) {
    return a == ACT_IDLE || a == ACT_WALKING || a == ACT_BRAKING || a == ACT_DECELERATING || a == ACT_PANTING
           || a == ACT_START_CROUCHING || a == ACT_CROUCHING || a == ACT_STOP_CROUCHING || a == ACT_TURNING_AROUND
           || a == ACT_FINISH_TURNING_AROUND || a == ACT_JUMP_LAND_STOP || a == ACT_FREEFALL_LAND_STOP
           || a == ACT_DOUBLE_JUMP_LAND_STOP || a == ACT_SIDE_FLIP_LAND_STOP || a == ACT_JUMP_LAND
           || a == ACT_FREEFALL_LAND || a == ACT_DOUBLE_JUMP_LAND || a == ACT_START_CRAWLING || a == ACT_CRAWLING
           || a == ACT_STOP_CRAWLING;
}

static s32 kt_air_ready(u32 a) {
    return a == ACT_JUMP || a == ACT_DOUBLE_JUMP || a == ACT_TRIPLE_JUMP || a == ACT_FREEFALL || a == ACT_SIDE_FLIP
           || a == ACT_BACKFLIP || a == ACT_LONG_JUMP || a == ACT_WALL_KICK_AIR || a == ACT_TOP_OF_POLE_JUMP
           || a == ACT_WATER_JUMP;
}

// The Legendary Blade (bhvKtBlade, katana_fighters.c) he can pull now, or NULL.
extern const BehaviorScript bhvKtBlade[];
static struct Object *kt_blade_near(struct MarioState *m) {
    struct ObjectNode *head = &gObjectLists[OBJ_LIST_GENACTOR];
    struct Object *obj, *best = NULL;
    f32 bestD = 190.0f * 190.0f;
    u32 a = m->action;

    if (gKtHeld || m->heldObj != NULL || gMarioObject == NULL
        || !(a == ACT_IDLE || a == ACT_WALKING || a == ACT_PANTING || a == ACT_BRAKING || a == ACT_DECELERATING
             || a == ACT_START_CROUCHING || a == ACT_STOP_CROUCHING || a == ACT_CROUCHING || a == ACT_START_SLEEPING
             || a == ACT_SLEEPING || a == ACT_WAKING_UP || a == ACT_TURNING_AROUND || a == ACT_FINISH_TURNING_AROUND
             || a == ACT_JUMP_LAND_STOP || a == ACT_FREEFALL_LAND_STOP)) {
        return NULL;
    }
    for (obj = (struct Object *) head->next; obj != (struct Object *) head; obj = (struct Object *) obj->header.next) {
        f32 dx, dz, d;

        if (obj->behavior != segmented_to_virtual(bhvKtBlade) || obj->oAction != 0 || !(obj->activeFlags & ACTIVE_FLAG_ACTIVE)) {
            continue;
        }
        dx = m->pos[0] - obj->oPosX;
        dz = m->pos[2] - obj->oPosZ;
        d = dx * dx + dz * dz;
        if (d < bestD && m->pos[1] < obj->oPosY + 60.0f && m->pos[1] > obj->oPosY - 60.0f) {
            bestD = d;
            best = obj;
        }
    }
    return best;
}

// (shotgun.c asks first: with the shotgun in his hands B still pulls the blade)
s32 studio_katana_blade_prompt(struct MarioState *m) {
    return kt_blade_near(m) != NULL;
}

void studio_katana_before_step(struct MarioState *m) {
    u32 a = m->action;
    struct Object *blade;

    // the pull prompt: B at a Legendary Blade in the floor
    blade = kt_blade_near(m);
    sKtPrompt = blade != NULL && gDialogID < 0;
    if (sKtPrompt && (m->input & INPUT_B_PRESSED)) {
        m->input &= ~INPUT_B_PRESSED;
        sKtPrompt = FALSE;
        kt_start_pull(blade);
        return;
    }
    if (!(m->action & ACT_FLAG_AIR)) {
        sKtAirSpinUsed = FALSE;
    }
    if (!gKtHeld || gKtSheathed || !(m->input & INPUT_B_PRESSED)) {
        return;
    }
    if (a == ACT_KT_SLASH) {
        sKtBuffered = TRUE;
        m->input &= ~INPUT_B_PRESSED;
        return;
    }
    if (kt_air_ready(a)) {
        m->input &= ~INPUT_B_PRESSED;
        if (!sKtAirSpinUsed) {
            set_mario_action(m, ACT_KT_AIR_SPIN, 0);
        }
        return;
    }
    if (kt_ground_ready(a)) {
        m->input &= ~INPUT_B_PRESSED;
        if (m->input & INPUT_Z_DOWN) {
            set_mario_action(m, ACT_KT_DASH, 0);
        } else if (m->forwardVel > 22.0f) {
            set_mario_action(m, ACT_KT_SLASH, 3);
        } else {
            if (m->input & INPUT_NONZERO_ANALOG) {
                m->faceAngle[1] = m->intendedYaw;
            }
            set_mario_action(m, ACT_KT_SLASH, 0);
        }
    }
}

// ---------------------------------------------------------------------------------------- his arms

static s32 kt_arms_free(struct MarioState *m) {
    u32 a = m->action;
    u32 group = a & ACT_GROUP_MASK;

    if (ACT_KT_IS(a)) {
        return TRUE;
    }
    if (group != ACT_GROUP_STATIONARY && group != ACT_GROUP_MOVING && group != ACT_GROUP_AIRBORNE) {
        return FALSE;
    }
    if (a & (ACT_FLAG_HANGING | ACT_FLAG_ON_POLE | ACT_FLAG_SWIMMING | ACT_FLAG_INTANGIBLE)) {
        return FALSE;
    }
    if (m->heldObj != NULL) {
        return FALSE;
    }
    return a != ACT_SLEEPING && a != ACT_START_SLEEPING && a != ACT_LEDGE_GRAB && a != ACT_LEDGE_CLIMB_SLOW_1
           && a != ACT_LEDGE_CLIMB_SLOW_2 && a != ACT_LEDGE_CLIMB_FAST && a != ACT_LEDGE_CLIMB_DOWN;
}

static void kt_pose_lerp(struct KtPoseDef *out, const struct KtPoseDef *a, const struct KtPoseDef *b, f32 t) {
    s32 j, k;

    out->twist = a->twist + (s16) ((s16) (b->twist - a->twist) * t);
    out->lean = a->lean + (s16) ((s16) (b->lean - a->lean) * t);
    for (j = 0; j < KT_JOINTS; j++) {
        for (k = 0; k < 3; k++) {
            if (a->j[j][k] == KT_KEEP || b->j[j][k] == KT_KEEP) {
                out->j[j][k] = (t < 0.5f) ? a->j[j][k] : b->j[j][k];
            } else {
                out->j[j][k] = a->j[j][k] + (s16) ((s16) (b->j[j][k] - a->j[j][k]) * t);
            }
        }
    }
}

/**
 * The pose his arms should be in this frame (into goal); returns how fast to get there (0..1).
 */
static f32 kt_goal_pose(struct MarioState *m, struct KtPoseDef *goal) {
    u32 a = m->action;
    s32 t = m->actionTimer;
    const struct KtCutDef *c;
    f32 p;
    s32 i;

    if (gKtDebugPose >= 100) {
        *goal = sKtTracks[(gKtDebugPose - 100) / 10][(gKtDebugPose - 100) % 10];
        return 1.0f;
    }
    if (gKtDebugPose > 0) {
        *goal = sKtPoses[gKtDebugPose - 1];
        return 1.0f;
    }
    switch (a) {
        case ACT_KT_SLASH:
            c = &sKtCuts[m->actionArg];
            i = m->actionArg == 3 ? 0 : m->actionArg;
            if (t < c->windup) {
                *goal = sKtTracks[i][0];
                return 0.6f;
            }
            p = KT_CLAMP((f32) (t - c->windup + 1) / c->swing, 0.0f, 1.0f) * (KT_TRACK_LEN - 1);
            i = KT_CLAMP((s32) p, 0, KT_TRACK_LEN - 2);
            kt_pose_lerp(goal, &sKtTracks[m->actionArg == 3 ? 0 : m->actionArg][i],
                         &sKtTracks[m->actionArg == 3 ? 0 : m->actionArg][i + 1], p - i);
            return t < c->windup + c->swing ? 1.0f : 0.25f;
        case ACT_KT_AIR_SPIN:
            *goal = sKtPoses[KP_SPIN];
            return 0.7f;
        case ACT_KT_DASH:
            *goal = sKtPoses[t < 12 ? KP_DASH_A : KP_DASH_B];
            return t < 12 ? 0.6f : 0.35f;
        case ACT_KT_PULL:
            *goal = sKtPoses[t < 42 ? KP_PULL : KP_RAISE];
            return t < 42 ? 0.5f : 0.45f;
        case ACT_KT_FLOURISH:
            *goal = sKtPoses[t < 22 ? KP_DASH_B : KP_SHEATHE];
            return 0.3f;
        case ACT_KT_PARRIED:
            *goal = sKtPoses[KP_RECOIL];
            return 0.6f;
    }
    if (a == ACT_IDLE || a == ACT_START_CROUCHING || a == ACT_CROUCHING) {
        *goal = sKtPoses[KP_READY];
        return 0.25f;
    }
    *goal = sKtPoses[KP_HOLD];
    return 0.3f;
}

static void kt_update_pose(struct MarioState *m) {
    struct KtPoseDef goal;
    f32 rate;
    f32 want = (gKtHeld && !gKtSheathed && kt_arms_free(m)) || m->action == ACT_KT_PULL ? 1.0f : 0.0f;

    rate = kt_goal_pose(m, &goal);
    if (sKtWeight <= 0.01f) {
        sKtNow = goal;
    } else {
        kt_pose_lerp(&sKtNow, &sKtNow, &goal, rate);
    }
    sKtWeight += (want - sKtWeight) * 0.35f;
    if (sKtWeight < 0.01f) {
        sKtWeight = 0.0f;
    }
}

static s16 kt_lerp_angle(s16 from, s16 to, f32 w) {
    return from + (s16) ((s16) (to - from) * w);
}

// Which of his animated parts is being drawn (0 = root), or -1 if it isn't Mario.
static s32 kt_mario_joint(void) {
    struct GraphNodeObject *gfx = gCurGraphNodeObject;
    u16 *base;

    if (gMarioObject == NULL || gfx != &gMarioObject->header.gfx || gfx->unk38.curAnim == NULL
        || gCurrAnimAttribute == NULL) {
        return -1;
    }
    base = segmented_to_virtual((void *) gfx->unk38.curAnim->index);
    return (s32) (gCurrAnimAttribute - base) / 6 - 2;
}

void studio_katana_anim_part(s16 *rot) {
    s32 joint, j, k;
    s16 v;

    if (sKtWeight <= 0.0f) {
        return;
    }
    joint = kt_mario_joint();
    if (joint == 2) {                      // the torso: the twist and the lean
        rot[0] += (s16) (sKtNow.twist * sKtWeight);
        rot[2] += (s16) (sKtNow.lean * sKtWeight);
        return;
    }
    if (joint == 3) {                      // the head looks where he's going
        rot[0] -= (s16) (sKtNow.twist * sKtWeight * 0.6f);
        return;
    }
    j = joint - KT_J0;
    if (joint < 0 || j < 0 || j >= KT_JOINTS) {
        return;
    }
    for (k = 0; k < 3; k++) {
        v = sKtNow.j[j][k];
        if (v != KT_KEEP) {
            rot[k] = kt_lerp_angle(rot[k], v, sKtWeight);
        }
    }
}

// ---------------------------------------------------------------------------------------- after his step

void studio_katana_after_step(struct MarioState *m) {
    if (gKtHitstop > 0 && !kt_duel_running()) {
        gKtHitstop--;                      // (a duel counts its own hit-stop down)
    }
    if (!gKtHeld && sKtWeight <= 0.0f && m->action != ACT_KT_PULL) {
        if (gKtPartCount > 0 || sKtTrailNow != NULL || gKtTrails[0].live || gKtTrails[1].live || gKtTrails[2].live
            || gKtTrails[3].live) {
            kt_fx_update();
        }
        return;
    }
    kt_update_pose(m);
    if (gKtHeld && !gKtSheathed && kt_arms_free(m)) {
        m->marioBodyState->handState = MARIO_HAND_FISTS;
    }
    if (!ACT_KT_IS(m->action)) {
        gKtAttack.active = FALSE;
        if (sKtTrailNow != NULL) {
            kt_trail_end();
        }
    } else {
        kt_strike_objects();
    }
    kt_fx_update();
}

// ---------------------------------------------------------------------------------------- the camera

s32 studio_katana_camera(struct Camera *c) {
    struct MarioState *m = gMarioState;
    s16 yaw, side;
    f32 d, h;

    if (sKtCamMode == 0) {
        return kt_duel_camera(c);
    }
    sKtCamTimer++;
    yaw = m->faceAngle[1];
    if (sKtCamMode == 1) {
        // the pull: low in front of him, off to his side, closing in; then looking up at the raised blade
        d = 520.0f - MIN(sKtCamTimer, 60) * 3.0f;
        h = sKtCamTimer < 42 ? 90.0f : 40.0f;
        side = 0x1800;
        c->pos[0] = m->pos[0] + sins((s16) (yaw + side)) * d;
        c->pos[1] = m->pos[1] + h;
        c->pos[2] = m->pos[2] + coss((s16) (yaw + side)) * d;
        c->focus[0] = m->pos[0];
        c->focus[1] = m->pos[1] + (sKtCamTimer < 42 ? 60.0f : 170.0f);
        c->focus[2] = m->pos[2];
        if (sKtCamTimer > 120) {
            sKtCamMode = 0;               // (never stuck on it)
        }
        return TRUE;
    }
    // the finale: close on him while he puts the blade away, the last one down behind him, a slow drift
    {
        s16 toFoe = yaw + 0x8000;
        f32 lead = 0.0f;

        if (sKtCamTarget != NULL) {
            toFoe = atan2s(sKtCamTarget->oPosZ - m->pos[2], sKtCamTarget->oPosX - m->pos[0]);
            lead = MIN(sqrtf((m->pos[0] - sKtCamTarget->oPosX) * (m->pos[0] - sKtCamTarget->oPosX)
                             + (m->pos[2] - sKtCamTarget->oPosZ) * (m->pos[2] - sKtCamTarget->oPosZ)) * 0.3f, 120.0f);
        }
        // (behind him from the fallen one's side, off to one side, drifting round)
        yaw = toFoe + 0x8000 + 0x1C00 - sKtCamTimer * 0x40;
        d = 330.0f + sKtCamTimer * 0.8f;
        c->pos[0] = m->pos[0] + sins(yaw) * d;
        c->pos[1] = m->pos[1] + 110.0f;
        c->pos[2] = m->pos[2] + coss(yaw) * d;
        // (not through a wall: as far as the way is clear)
        {
            Vec3f from, to;
            f32 free;

            vec3f_set(from, m->pos[0], m->pos[1] + 110.0f, m->pos[2]);
            vec3f_copy(to, c->pos);
            free = studio_shotgun_ray_clear(from, to);
            if (free < d) {
                d = MAX(free - 40.0f, 120.0f);
                c->pos[0] = m->pos[0] + sins(yaw) * d;
                c->pos[2] = m->pos[2] + coss(yaw) * d;
            }
        }
        c->focus[0] = m->pos[0] + sins(toFoe) * lead;
        c->focus[1] = m->pos[1] + 90.0f;
        c->focus[2] = m->pos[2] + coss(toFoe) * lead;
    }
    if (sKtCamTimer > 150) {
        sKtCamMode = 0;
    }
    return TRUE;
}

