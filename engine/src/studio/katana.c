void kt_fx_confetti(f32 x, f32 y, f32 z, s32 count) {
    static const u8 cols[6][3] = { { 255, 110, 170 }, { 255, 230, 90 }, { 120, 220, 255 }, { 170, 255, 170 },
                                   { 210, 160, 255 }, { 255, 255, 255 } };
    struct KtPart *p;
    s32 i, c;

    for (i = 0; i < count; i++) {
        p = kt_part(FX_CONFETTI);
        vec3f_set(p->pos, x + kt_rand_s() * 30.0f, y + kt_rand_s() * 30.0f, z + kt_rand_s() * 30.0f);
        vec3f_set(p->vel, kt_rand_s() * 16.0f, 14.0f + kt_rand() * 22.0f, kt_rand_s() * 16.0f);
        p->size = 9.0f + kt_rand() * 7.0f;
        p->life = p->maxLife = 60 + (random_u16() % 40);
        p->rot = random_u16();
        p->rotVel = (s16) (kt_rand_s() * 0x1400);
        c = random_u16() % 6;
        p->r = cols[c][0], p->g = cols[c][1], p->b = cols[c][2];
    }
}

