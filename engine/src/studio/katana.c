static void kt_fx_streak(Vec3f from, Vec3f to) {
    struct KtPart *p = kt_part(FX_STREAK);

    vec3f_copy(p->pos, from);
    vec3f_copy(p->vel, to);          // (a streak keeps its other end here)
    p->size = 60.0f;
    p->life = p->maxLife = 14;
}

// the floor under a confetti piece (it lands on what is there, not on y 0 like in the cafe)
static f32 kt_floor_at(f32 x, f32 y, f32 z) {
    struct Surface *floor;
    f32 h = find_floor(x, y + 40.0f, z, &floor);

    return floor != NULL ? h : -11000.0f;
}

void kt_fx_update(void) {
    struct KtPart *p;
    struct KtTrail *t;
    s32 i, n = 0;
    f32 fy;

    for (i = 0; i < KT_MAX_PARTS; i++) {
        p = &gKtParts[i];
        if (p->life <= 0) {
            continue;
        }
        p->life--;
        n++;
        if (p->kind == FX_STREAK) {
            continue;
        }
        p->pos[0] += p->vel[0];
        p->pos[1] += p->vel[1];
        p->pos[2] += p->vel[2];
        p->rot += p->rotVel;
        switch (p->kind) {
            case FX_SPARK:
                p->vel[1] -= 2.5f;
                p->vel[0] *= 0.86f;
                p->vel[2] *= 0.86f;
                break;
            case FX_CONFETTI:
                p->vel[1] = MAX(p->vel[1] - 1.6f, -5.0f);
                p->vel[0] *= 0.94f;
                p->vel[2] *= 0.94f;
                p->pos[0] += sins(p->rot) * 1.5f;
                if (p->vel[1] < 0.0f && (p->life & 3) == 0) {
                    fy = kt_floor_at(p->pos[0], p->pos[1], p->pos[2]) + 4.0f;
                    if (p->pos[1] < fy) {
                        p->pos[1] = fy;
                        p->vel[0] = p->vel[1] = p->vel[2] = 0.0f;
                        p->rotVel = 0;
                    }
                }
                break;
            case FX_HEART:
                p->vel[0] += sins(p->life * 0x900) * 0.3f;
                break;
        }
    }
    gKtPartCount = n;
    for (i = 0; i < KT_TRAILS; i++) {
        t = &gKtTrails[i];
        if (t->live && t != sKtTrailNow) {
            if (++t->fade >= KT_TRAIL_FADE) {
                t->live = FALSE;
            }
        }
    }
}

static struct KtTrail *kt_trail_start(struct MarioState *m, s16 a0, s16 a1, s16 roll, s16 pitch, u8 color) {
    struct KtTrail *t = &gKtTrails[sKtTrailNext];

    sKtTrailNext = (sKtTrailNext + 1) % KT_TRAILS;
    vec3f_set(t->origin, m->pos[0], m->pos[1] + 80.0f, m->pos[2]);
    t->yaw = m->faceAngle[1];
    t->roll = roll;
    t->pitch = pitch;
    t->a0 = a0;
    t->a1 = a1;
    t->progress = 0.0f;
    t->fade = 0;
    t->r0 = 40.0f;
    t->r1 = 250.0f;
    t->live = TRUE;
    t->color = color;
    sKtTrailNow = t;
    gStudioKatanaDraw = TRUE;
    return t;
}

static void kt_trail_end(void) {
    sKtTrailNow = NULL;
}

