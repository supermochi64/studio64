// the crescents: one per cut (a few can fade at once)
struct KtTrail {
    Vec3f origin;
    s16 yaw, roll, pitch;
    s16 a0, a1;          // the whole sweep
    f32 progress;        // how far the blade has got (0..1)
    s16 fade;            // frames since the swing ended (drawn while < KT_TRAIL_FADE)
    f32 r0, r1;
    u8 live;
    u8 color;            // 0 electric blue, 1 pink (the spin), 2 gold (the dash)
};
#define KT_TRAILS 4
#define KT_TRAIL_FADE 9
struct KtTrail gKtTrails[KT_TRAILS];
static s16 sKtTrailNext = 0;
static struct KtTrail *sKtTrailNow = NULL;

static f32 kt_rand(void) {
    return random_float();
}

static f32 kt_rand_s(void) {
    return random_float() * 2.0f - 1.0f;
}

static struct KtPart *kt_part(s32 kind) {
    s32 i, oldest = 0;

    gStudioKatanaDraw = TRUE;
    for (i = 0; i < KT_MAX_PARTS; i++) {
        if (gKtParts[i].life <= 0) {
            gKtParts[i].kind = kind;
            return &gKtParts[i];
        }
        if (gKtParts[i].life < gKtParts[oldest].life) {
            oldest = i;
        }
    }
    gKtParts[oldest].kind = kind;
    return &gKtParts[oldest];
}

void kt_fx_sparks(f32 x, f32 y, f32 z, s32 count) {
    struct KtPart *p;
    s32 i;

    for (i = 0; i < count; i++) {
        p = kt_part(FX_SPARK);
        vec3f_set(p->pos, x, y, z);
        vec3f_set(p->vel, kt_rand_s() * 22.0f, kt_rand_s() * 18.0f + 8.0f, kt_rand_s() * 22.0f);
        p->size = 10.0f + kt_rand() * 14.0f;
        p->life = p->maxLife = 8 + (random_u16() % 8);
        p->r = 255, p->g = 230, p->b = 160;
    }
    // a big bright flash in the middle
    p = kt_part(FX_GLINT);
    vec3f_set(p->pos, x, y, z);
    vec3f_set(p->vel, 0, 0, 0);
    p->size = 90.0f;
    p->life = p->maxLife = 6;
    p->rot = random_u16();
    p->rotVel = 0x800;
    p->r = 255, p->g = 255, p->b = 255;
}

