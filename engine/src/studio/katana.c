/**
 * Katana Mario, ported from Shoggoth World (src/game/shoggoth/overlay/katana.c, its maid cafe;
 * docs/katana.md here). studio/katana.h is the interface; the fighters, the duel and the Legendary Blade
 * in the floor are studio/katana_fighters.c.
 *
 * The moves are Mario actions (ACT_KT_*: mario.c hands them to studio_katana_action); his arms are posed
 * over whatever his body animation does (studio_katana_anim_part) from IK-solved tables (Shoggoth World's
 * tools/shoggoth/katana_poses.py, copied by tools/katana_extract.py as katana/katana_poses.h): a cut is a
 * track of poses the blade sweeps through. The blade rides his right fist -- drawn from the fist's own
 * animated part (studio_katana_part_drawn) instead of the hack's SH_MGEO_RHAND node, so any Mario model
 * carries it. Everything flashy is drawn in world space once a frame from his root: each cut's crescent
 * (a fading arc the width of the blade), sparks, the blade's glints, confetti and hearts, and the manga
 * words (NANI?!, ズバッ, ドン!, キン!).
 *
 * Differences to the N64 original: resident code instead of the cafe's overlay; direct hooks instead of
 * gShHooks; besides the fighters (who test themselves against gKtAttack), a cut hits every object in its
 * arc the way a shotgun blast does (studio_weapon_react_kind / studio_weapon_react, shotgun.c), the dash's
 * cuts landing at its click; the blade, the rule and the story decide when he has it.
 */
