static s32 act_kt_pull(struct MarioState *m) {
    s32 t = m->actionTimer;
    struct Object *k = sKtPullObj;
    s16 yaw;

    if (k == NULL || k->activeFlags == ACTIVE_FLAG_DEACTIVATED) {
        sKtCamMode = 0;
        return set_mario_action(m, ACT_IDLE, 0);
    }
    mario_set_forward_vel(m, 0.0f);
    if (t == 0) {
        yaw = atan2s(k->oPosZ - m->pos[2], k->oPosX - m->pos[0]);
        m->faceAngle[1] = yaw;
        m->pos[0] = k->oPosX - sins(yaw) * 70.0f;
        m->pos[2] = k->oPosZ - coss(yaw) * 70.0f;
        vec3f_set(sKtPullHome, k->oPosX, k->oPosY, k->oPosZ);
        vec3f_copy(sKtPullMario, m->pos);
        set_mario_animation(m, MARIO_ANIM_GRAB_HEAVY_OBJECT);
        // (straight into its last frame, the heave the arms are solved on: its first frames kick a leg up, the
        // fists off the hilt)
        set_anim_to_frame(m, 36);
        sKtCamMode = 1;
        sKtCamTimer = 0;
        play_sound(SOUND_MARIO_UH2, m->marioObj->header.gfx.cameraToObject);
    }
    if (t < 42) {
        // both fists on the hilt: Mario steps so his right fist is over it (at most 60 from where he began), the
        // blade's depth takes up the height (+-30) -- the fist as drawn last frame, his pose settling in
        if (t >= 2 && gKtFistFrame >= (s32) gGlobalTimer - 2) {
            f32 dx = k->oPosX - gKtFistWorld[0], dz = k->oPosZ - gKtFistWorld[2];
            f32 ox, oz, d;

            m->pos[0] += dx * 0.5f;
            m->pos[2] += dz * 0.5f;
            ox = m->pos[0] - sKtPullMario[0];
            oz = m->pos[2] - sKtPullMario[2];
            d = sqrtf(ox * ox + oz * oz);
            if (d > 60.0f) {
                m->pos[0] = sKtPullMario[0] + ox * 60.0f / d;
                m->pos[2] = sKtPullMario[2] + oz * 60.0f / d;
            }
            k->oPosY += (KT_CLAMP(gKtFistWorld[1] - KT_HILT_Y, sKtPullHome[1] - 30.0f, sKtPullHome[1] + 30.0f)
                         - k->oPosY) * 0.5f;
        }
        if (gKtFistFrame >= (s32) gGlobalTimer - 2) {
            f32 gx = k->oPosX - gKtFistWorld[0], gy = k->oPosY + KT_HILT_Y - gKtFistWorld[1];
            f32 gz = k->oPosZ - gKtFistWorld[2];
            gKtPullGap = sqrtf(gx * gx + gy * gy + gz * gz);
        }
        vec3f_copy(m->marioObj->header.gfx.pos, m->pos);
        // the struggle: it won't come
        if (t > 10) {
            m->marioObj->header.gfx.pos[0] = m->pos[0] + kt_rand_s() * 2.5f;
            m->marioObj->header.gfx.pos[2] = m->pos[2] + kt_rand_s() * 2.5f;
            k->oFaceAngleRoll = (s16) (kt_rand_s() * 0x200);
            if ((t % 10) == 0) {
                play_sound(t == 30 ? SOUND_MARIO_UH2 : SOUND_ACTION_TERRAIN_STEP, m->marioObj->header.gfx.cameraToObject);
            }
        }
        m->actionTimer++;
        return FALSE;
    }
    if (t == 42) {
        // ... and out it comes
        k->oPosY = sKtPullHome[1];
        k->oAction = 1;
        k->oFaceAngleRoll = 0;
        kt_take(TRUE);
        sKtByRule = FALSE;
        set_mario_animation(m, MARIO_ANIM_STAR_DANCE);
        play_sound(SOUND_MENU_STAR_SOUND, gDefaultSoundArgs);
        play_sound(SOUND_MARIO_HERE_WE_GO, m->marioObj->header.gfx.cameraToObject);
        kt_fx_sparks(k->oPosX, k->oPosY + 20.0f, k->oPosZ, 20);
        kt_fx_confetti(k->oPosX, k->oPosY + 60.0f, k->oPosZ, 10);
        kt_event("pulled", k->unused2, 0);
    }
    if (t == 62) {
        kt_fx_glint(m->pos[0], m->pos[1] + 250.0f, m->pos[2]);
        play_sound(SOUND_GENERAL_SHORT_STAR, gDefaultSoundArgs);
    }
    if (t >= 86) {
        sKtPullDone = TRUE;
        sKtCamMode = 0;
        return set_mario_action(m, ACT_IDLE, 0);
    }
    m->actionTimer++;
    return FALSE;
}

static s32 act_kt_flourish(struct MarioState *m) {
    s32 t = m->actionTimer;

    mario_set_forward_vel(m, 0.0f);
    if (t == 0) {
        set_mario_animation(m, MARIO_ANIM_FIRST_PUNCH);
        play_sound(SOUND_GENERAL_SWISH_AIR, m->marioObj->header.gfx.cameraToObject);
    }
    if (t == 18) {
        set_mario_animation(m, MARIO_ANIM_IDLE_HEAD_CENTER);
    }
    if (t == 38) {
        gKtSheathed = TRUE;
        play_sound(SOUND_GENERAL_BIG_CLOCK, m->marioObj->header.gfx.cameraToObject);
        kt_fx_glint(m->pos[0] + sins(m->faceAngle[1] + 0x4000) * 40.0f, m->pos[1] + 50.0f,
                    m->pos[2] + coss(m->faceAngle[1] + 0x4000) * 40.0f);
    }
    if (t >= 50) {
        // (in Studio 64 he keeps the blade: sheathed now, ready again on the next B)
        gKtSheathed = FALSE;
        return set_mario_action(m, ACT_IDLE, 0);
    }
    perform_ground_step(m);
    m->actionTimer++;
    return FALSE;
}

s32 studio_katana_action(struct MarioState *m) {
    switch (m->action) {
        case ACT_KT_PULL:     return act_kt_pull(m);
        case ACT_KT_SLASH:    return act_kt_slash(m);
        case ACT_KT_AIR_SPIN: return act_kt_air_spin(m);
        case ACT_KT_DASH:     return act_kt_dash(m);
        case ACT_KT_FLOURISH: return act_kt_flourish(m);
        case ACT_KT_PARRIED:  return act_kt_parried(m);
    }
    return set_mario_action(m, ACT_IDLE, 0);
}

