static void kt_freeze_anim(struct MarioState *m) {
    struct GraphNodeObject_sub *a = &m->marioObj->header.gfx.unk38;

    if (a->animAccel == 0) {
        a->animFrame--;
    } else {
        a->animFrameAccelAssist -= a->animAccel;
        a->animFrame = (s16) (a->animFrameAccelAssist >> 16);
    }
}

static s32 kt_ground_move(struct MarioState *m, f32 decel) {
    s32 step;

    m->forwardVel = approach_f32(m->forwardVel, 0.0f, decel, decel);
    mario_set_forward_vel(m, m->forwardVel);
    step = perform_ground_step(m);
    if (step == GROUND_STEP_LEFT_GROUND) {
        set_mario_action(m, ACT_FREEFALL, 0);
        return TRUE;
    }
    return FALSE;
}

static s32 act_kt_slash(struct MarioState *m) {
    const struct KtCutDef *c = &sKtCuts[m->actionArg];
    s32 t = m->actionTimer;
    s32 swingEnd = c->windup + c->swing;
    f32 p;

    if (gKtHitstop > 0) {
        kt_freeze_anim(m);
        return FALSE;
    }
    if (t == 0) {
        set_mario_animation(m, c->anim);
        m->forwardVel = c->lunge;
        sKtBuffered = FALSE;
        kt_attack_begin(m, m->actionArg == 3 ? KT_CUT_LUNGE : KT_CUT_1 + m->actionArg, c->reach, c->halfArc, c->damage);
    }
    if (t == c->windup) {
        play_mario_sound(m, SOUND_ACTION_SIDE_FLIP_UNK, c->voice);
        play_sound(SOUND_GENERAL_SWISH_AIR, m->marioObj->header.gfx.cameraToObject);
        kt_trail_start(m, c->a0, c->a1, c->tiltRoll, c->tiltPitch, 0);
    }
    if (t >= c->windup && t < swingEnd) {
        p = (f32) (t - c->windup + 1) / c->swing;
        if (sKtTrailNow != NULL) {
            sKtTrailNow->progress = p;
            vec3f_set(sKtTrailNow->origin, m->pos[0], m->pos[1] + 80.0f, m->pos[2]);
        }
        kt_attack_live(m, m->faceAngle[1]);
    } else {
        gKtAttack.active = FALSE;
        if (t == swingEnd) {
            kt_trail_end();
        }
    }
    if (kt_ground_move(m, m->actionArg == 2 ? 4.0f : 3.0f)) {
        gKtAttack.active = FALSE;
        kt_trail_end();
        return TRUE;
    }
    // (the stick turns him a little between cuts)
    if (t < c->windup && (m->input & INPUT_NONZERO_ANALOG)) {
        m->faceAngle[1] = approach_s16_symmetric(m->faceAngle[1], m->intendedYaw, 0x1800);
    }
    // the combo: B during a cut chains the next one as soon as this one has swung
    if (t >= swingEnd + 1 && sKtBuffered && m->actionArg < 2) {
        return set_mario_action(m, ACT_KT_SLASH, m->actionArg + 1);
    }
    if (t >= swingEnd + c->recover) {
        return set_mario_action(m, ACT_IDLE, 0);
    }
    // cancel the recovery into a jump
    if (t >= swingEnd + 3 && (m->input & INPUT_A_PRESSED)) {
        return set_mario_action(m, ACT_JUMP, 0);
    }
    m->actionTimer++;
    return FALSE;
}

static s32 act_kt_air_spin(struct MarioState *m) {
    s32 t = m->actionTimer;
    s32 step;

    if (gKtHitstop > 0) {
        kt_freeze_anim(m);
        m->marioObj->header.gfx.angle[1] = m->faceAngle[1] + sKtSpin;
        return FALSE;
    }
    if (t == 0) {
        set_mario_animation(m, MARIO_ANIM_TWIRL);
        m->vel[1] = MAX(m->vel[1], 22.0f);
        sKtSpin = 0;
        sKtAirSpinUsed = TRUE;
        play_mario_sound(m, SOUND_ACTION_SPIN, SOUND_MARIO_YAHOO);
        kt_attack_begin(m, KT_CUT_SPIN, 270.0f, 0x7FFF, 1);
        kt_trail_start(m, 0, DEG(359), 0, 0, 1);
    }
    // two full turns in 14 frames, hanging in the air
    if (t < 14) {
        sKtSpin += 0x1250;
        if (sKtTrailNow != NULL) {
            sKtTrailNow->a0 = sKtSpin - DEG(300);
            sKtTrailNow->a1 = sKtSpin;
            sKtTrailNow->progress = 1.0f;
            vec3f_set(sKtTrailNow->origin, m->pos[0], m->pos[1] + 70.0f, m->pos[2]);
            sKtTrailNow->yaw = m->faceAngle[1];
        }
        kt_attack_live(m, m->faceAngle[1]);
        if (t == 7) {
            play_sound(SOUND_ACTION_TWIRL, m->marioObj->header.gfx.cameraToObject);
            sKtAttackId++;                    // (the second turn cuts again)
            gKtAttack.id = sKtAttackId;
        }
        m->vel[1] = MAX(m->vel[1] - 1.2f, -8.0f);
    } else {
        gKtAttack.active = FALSE;
        kt_trail_end();
        sKtSpin = approach_s16_symmetric(sKtSpin, 0, 0x2000);
        m->vel[1] -= 4.0f;
    }
    m->forwardVel *= 0.96f;
    mario_set_forward_vel(m, m->forwardVel);
    step = perform_air_step(m, 0);
    m->marioObj->header.gfx.angle[1] = m->faceAngle[1] + sKtSpin;
    if (step == AIR_STEP_LANDED) {
        gKtAttack.active = FALSE;
        kt_trail_end();
        sKtSpin = 0;
        return set_mario_action(m, ACT_FREEFALL_LAND, 0);
    }
    if (step == AIR_STEP_HIT_WALL) {
        mario_set_forward_vel(m, 0.0f);
    }
    m->actionTimer++;
    return FALSE;
}

static s32 act_kt_dash(struct MarioState *m) {
    s32 t = m->actionTimer;
    Vec3f from;

    if (gKtHitstop > 0 && t > 12) {
        kt_freeze_anim(m);
        return FALSE;
    }
    if (t == 0) {
        set_mario_animation(m, MARIO_ANIM_START_CROUCHING);
        m->forwardVel = 0.0f;
        gKtDashClick = FALSE;
        kt_attack_begin(m, KT_CUT_DASH, 170.0f, 0x7FFF, 2);
        play_sound(SOUND_GENERAL_SWISH_WATER, m->marioObj->header.gfx.cameraToObject);
        if (m->input & INPUT_NONZERO_ANALOG) {
            m->faceAngle[1] = m->intendedYaw;
        }
    }
    if (t < 6) {
        // the draw stance: a breath
        m->forwardVel = 0.0f;
        if (t == 4) {
            kt_fx_glint(m->pos[0] + sins(m->faceAngle[1] + 0x3000) * 40.0f, m->pos[1] + 60.0f,
                        m->pos[2] + coss(m->faceAngle[1] + 0x3000) * 40.0f);
        }
    } else if (t < 12) {
        // through them: ~650 units in six frames
        if (t == 6) {
            set_mario_animation(m, MARIO_ANIM_RUNNING);
            play_mario_sound(m, SOUND_ACTION_SIDE_FLIP_UNK, SOUND_MARIO_HOOHOO);
            m->forwardVel = 110.0f;
        }
        vec3f_copy(from, m->pos);
        from[1] += 70.0f;
        kt_attack_live(m, m->faceAngle[1]);
        if (kt_ground_move(m, 0.0f)) {
            gKtAttack.active = FALSE;
            return TRUE;
        }
        {
            Vec3f to;

            vec3f_copy(to, m->pos);
            to[1] += 70.0f;
            kt_fx_streak(from, to);
        }
        m->actionTimer++;
        return FALSE;
    } else {
        gKtAttack.active = FALSE;
        if (t == 12) {
            set_mario_animation(m, MARIO_ANIM_STOP_SKID);
            m->forwardVel = 30.0f;
        }
        if (t == 22) {
            // the click: the blade back in its place, and every cut lands at once
            gKtDashClick = TRUE;
            play_sound(SOUND_GENERAL_BIG_CLOCK, m->marioObj->header.gfx.cameraToObject);
            kt_land_pending();
        }
        if (t == 23) {
            gKtDashClick = FALSE;
        }
    }
    if (kt_ground_move(m, 4.0f)) {
        return TRUE;
    }
    if (t >= 32) {
        return set_mario_action(m, ACT_IDLE, 0);
    }
    m->actionTimer++;
    return FALSE;
}

static s32 act_kt_parried(struct MarioState *m) {
    if (m->actionTimer == 0) {
        set_mario_animation(m, MARIO_ANIM_SOFT_BACK_KB);
        m->forwardVel = -18.0f;
    }
    kt_ground_move(m, 2.0f);
    if (m->actionTimer++ >= 16) {
        return set_mario_action(m, ACT_IDLE, 0);
    }
    return FALSE;
}

