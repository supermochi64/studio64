static void kt_attack_begin(struct MarioState *m, s32 kind, f32 reach, s16 halfArc, s32 damage) {
    sKtAttackId++;
    gKtAttack.id = sKtAttackId;
    gKtAttack.kind = kind;
    gKtAttack.reach = reach;
    gKtAttack.halfArc = halfArc;
    gKtAttack.damage = damage;
    gKtAttack.active = FALSE;
    gKtSwings++;
}

static void kt_attack_live(struct MarioState *m, s16 yaw) {
    gKtAttack.active = TRUE;
    gKtAttack.x = m->pos[0];
    gKtAttack.y = m->pos[1] + 80.0f;
    gKtAttack.z = m->pos[2];
    gKtAttack.yaw = yaw;
}

s32 kt_attack_hits(struct Object *obj, f32 radius, f32 height) {
    f32 dx, dz, d, dy;
    s16 ang;

    if (!gKtAttack.active) {
        return FALSE;
    }
    dx = obj->oPosX - gKtAttack.x;
    dz = obj->oPosZ - gKtAttack.z;
    dy = gKtAttack.y - obj->oPosY;
    d = sqrtf(dx * dx + dz * dz);
    if (d > gKtAttack.reach + radius || dy < -80.0f || dy > height + 80.0f) {
        return FALSE;
    }
    if (gKtAttack.halfArc >= 0x7F00 || d < 60.0f) {
        return TRUE;
    }
    ang = atan2s(dz, dx) - gKtAttack.yaw;
    // (the target's own width widens the arc a little)
    return abs_angle_diff(ang, 0) <= gKtAttack.halfArc + (s16) (radius / MAX(d, 1.0f) * 10430.0f);
}

void kt_on_hit(struct Object *obj, s32 finisher) {
    struct MarioState *m = gMarioState;
    f32 y = obj->oPosY + 110.0f;

    gKtHits++;
    gKtHitstop = finisher ? 9 : 4;
    kt_fx_sparks(obj->oPosX, y, obj->oPosZ, finisher ? 18 : 10);
    if (finisher) {
        kt_fx_word(obj->oPosX, y + 120.0f, obj->oPosZ, KT_WORD_DON, 24);
        set_camera_shake_from_hit(SHAKE_SMALL_DAMAGE);
    } else if ((random_u16() & 1) || gKtAttack.kind == KT_CUT_3) {
        kt_fx_word(obj->oPosX + kt_rand_s() * 40.0f, y + 90.0f, obj->oPosZ, KT_WORD_ZUBA, 16);
    }
    set_camera_shake_from_hit(SHAKE_ATTACK);
    set_fov_shake(finisher ? 0x200 : 0x100, 0x30, 0x8000);
    play_sound(SOUND_ACTION_HIT_3, m->marioObj->header.gfx.cameraToObject);
    play_sound(finisher ? SOUND_OBJ_POUNDING1_HIGHPRIO : SOUND_ACTION_BOUNCE_OFF_OBJECT, obj->header.gfx.cameraToObject);
}

void kt_on_parry(struct Object *obj) {
    struct MarioState *m = gMarioState;

    kt_fx_sparks((obj->oPosX + m->pos[0]) / 2, m->pos[1] + 100.0f, (obj->oPosZ + m->pos[2]) / 2, 16);
    play_sound(SOUND_GENERAL_CLAM_SHELL1, m->marioObj->header.gfx.cameraToObject);
    set_camera_shake_from_hit(SHAKE_ATTACK);
    gKtHitstop = 5;
    gKtAttack.active = FALSE;
    if ((m->action & ACT_GROUP_MASK) != ACT_GROUP_AIRBORNE && !(m->action & ACT_FLAG_AIR)) {
        set_mario_action(m, ACT_KT_PARRIED, 0);
    }
}

// ---------------------------------------------------------------------------------------- everything else
// (the Studio 64 part: a cut hits every object in its arc the way a shotgun blast does -- goombas fall,
// bob-ombs go off, boxes break, armour sparks; the dash's cuts land at its click)

#define KT_STRUCK 24
static struct { struct Object *obj; u16 id; u8 pending; s8 kind; } sKtStruck[KT_STRUCK];
static s32 sKtStruckNext = 0;
static s32 sKtLastKinds[8];             // (tests: the reactions of the last cut's hits)
static s32 sKtLastKindCount = 0;

static s32 kt_struck_by(struct Object *obj, u16 id) {
    s32 i;

    for (i = 0; i < KT_STRUCK; i++) {
        if (sKtStruck[i].obj == obj && sKtStruck[i].id == id) {
            return TRUE;
        }
    }
    return FALSE;
}

static void kt_land_on(struct Object *obj, s32 kind) {
    Vec3f dir;
    f32 dx = obj->oPosX - gMarioState->pos[0], dz = obj->oPosZ - gMarioState->pos[2];
    f32 d = sqrtf(dx * dx + dz * dz);

    vec3f_set(dir, d > 1.0f ? dx / d : 0.0f, 0.15f, d > 1.0f ? dz / d : 1.0f);
    studio_weapon_react(obj, kind, dir);
    sKtObjHits++;
    if (sKtLastKindCount < 8) {
        sKtLastKinds[sKtLastKindCount++] = kind;
    }
    if (kind == STUDIO_WEAPON_ARMOUR) {
        // (it only glances off: sparks and a clang)
        kt_fx_sparks(obj->oPosX, obj->oPosY + obj->hitboxHeight * 0.5f, obj->oPosZ, 10);
        kt_fx_word(obj->oPosX, obj->oPosY + obj->hitboxHeight + 80.0f, obj->oPosZ, KT_WORD_KIN, 18);
        play_sound(SOUND_GENERAL_CLAM_SHELL1, obj->header.gfx.cameraToObject);
        gKtHitstop = MAX(gKtHitstop, 3);
    } else {
        kt_on_hit(obj, FALSE);
    }
}

static void kt_strike_objects(void) {
    static const u8 lists[] = { OBJ_LIST_PUSHABLE, OBJ_LIST_GENACTOR, OBJ_LIST_DESTRUCTIVE, OBJ_LIST_LEVEL,
                                OBJ_LIST_DEFAULT, OBJ_LIST_SURFACE, OBJ_LIST_POLELIKE };
    struct ObjectNode *head;
    struct Object *obj;
    s32 li, kind, n = 0;

    if (!gKtAttack.active) {
        return;
    }
    for (li = 0; li < (s32) sizeof(lists); li++) {
        head = &gObjectLists[lists[li]];
        for (obj = (struct Object *) head->next; obj != (struct Object *) head; obj = (struct Object *) obj->header.next) {
            if (kt_fighter_is(obj) || kt_struck_by(obj, gKtAttack.id)) {
                continue;
            }
            kind = studio_weapon_react_kind(obj);
            if (kind == STUDIO_WEAPON_NONE) {
                continue;
            }
            if (!kt_attack_hits(obj, obj->hitboxRadius, obj->hitboxHeight)) {
                continue;
            }
            if (n == 0) {
                sKtLastKindCount = 0;
            }
            sKtStruck[sKtStruckNext].obj = obj;
            sKtStruck[sKtStruckNext].id = gKtAttack.id;
            sKtStruck[sKtStruckNext].kind = kind;
            sKtStruck[sKtStruckNext].pending = gKtAttack.kind == KT_CUT_DASH;
            sKtStruckNext = (sKtStruckNext + 1) % KT_STRUCK;
            n++;
            if (gKtAttack.kind != KT_CUT_DASH) {
                kt_land_on(obj, kind);
            }
        }
    }
}

// the dash's click: every object it went through takes its cut now
static void kt_land_pending(void) {
    s32 i;

    for (i = 0; i < KT_STRUCK; i++) {
        if (sKtStruck[i].pending) {
            sKtStruck[i].pending = FALSE;
            if (sKtStruck[i].obj != NULL && sKtStruck[i].obj->activeFlags != ACTIVE_FLAG_DEACTIVATED) {
                kt_land_on(sKtStruck[i].obj, sKtStruck[i].kind);
            }
        }
    }
}

