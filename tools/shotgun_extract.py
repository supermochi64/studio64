# Usage: python3 tools/shotgun_extract.py   (needs Shoggoth World's built tree: ../sm64-master or SHOGGOTH_DIR)
# Extract the shotgun, its effects and the hood gangsters from Shoggoth World's generated hood data
# into Studio 64 (engine/src/studio/shotgun/). Read-only on sm64-master. The output ships with Studio 64;
# run it through tools/shoggoth/refresh.mjs (npm run shoggoth:refresh), which then takes the game's own
# data back out (the gangsters' Goomba feet and faces: tools/shoggoth/split_vanilla.py).
import re, os, shutil, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SM = os.path.abspath(os.environ.get('SHOGGOTH_DIR') or os.path.join(ROOT, '..', 'sm64-master'))
OUT = os.path.join(ROOT, 'engine', 'src', 'studio', 'shotgun')
if not all(os.path.exists(os.path.join(SM, f)) for f in ['levels/hood/texture.inc.c', 'levels/hood/model.inc.c', 'levels/hood/geo.c']):
    print('No Shoggoth World checkout with the hood level at %s: no Shotgun Mario models (that is fine)' % SM)
    sys.exit(0)
os.makedirs(OUT, exist_ok=True)
src = ''
for f in ['levels/hood/texture.inc.c', 'levels/hood/model.inc.c', 'levels/hood/geo.c']:
    src += open(os.path.join(SM, f)).read() + '\n'
defs = {}
order = []
pat = re.compile(r'^((?:ALIGNED8 )?(?:static )?const (\w+) (\w+)(\[\])? = (?:\{|gdSPDefLights1\())', re.M)
for m in pat.finditer(src):
    start = m.start()
    end_tok = '\n};' if m.group(4) else ');'
    end = src.index(end_tok, m.end()) + len(end_tok)
    defs[m.group(3)] = src[start:end]
    order.append(m.group(3))
roots = sys.argv[1:] or ['hood_sg_body_dl_opaque', 'hood_sg_pump_dl_opaque', 'hood_shotgun_dl_opaque', 'hood_tex_sg_hole', 'hood_tex_sg_smoke',
         'hood_tex_sg_star', 'hood_shotgun_geo', 'hood_gangster0_geo', 'hood_gangster1_geo', 'hood_gangster2_geo',
         'hood_hood_bullet_geo']
need = set()
def visit(n):
    if n in need: return
    need.add(n)
    for ident in set(re.findall(r'\b(hood_\w+)\b', defs[n])):
        if ident in defs and ident != n:
            visit(ident)
for r in roots: visit(r)
missing = set()
for n in need:
    for ident in re.findall(r'\b([a-z_][a-z0-9_]*_(?:dl|geo|seg8\w*)\w*)\b', defs[n]):
        if not ident.startswith('hood_'): missing.add(ident)
print('external refs:', sorted(missing))
def fix(text):
    # textures: copy the include files next to us
    def inc(m):
        p = m.group(1)
        base = os.path.basename(p)
        for cand in [os.path.join(SM, p), os.path.join(SM, 'build/us', p)]:
            if os.path.exists(cand):
                shutil.copy(cand, os.path.join(OUT, base)); break
        else:
            raise SystemExit('no texture ' + p)
        return '#include "studio/shotgun/%s"' % base
    text = re.sub(r'#include "(levels/hood/[^"]+)"', inc, text)
    # no hood fog in other levels
    text = re.sub(r'\n\s*gsDPSetFogColor\([^)]*\),', '', text)
    text = re.sub(r'\n\s*gsSPFogPosition\([^)]*\),', '', text)
    text = re.sub(r'\n\s*gsSP(?:Set|Clear)GeometryMode\(G_FOG\),', '', text)
    text = text.replace('gsDPSetCycleType(G_CYC_2CYCLE)', 'gsDPSetCycleType(G_CYC_1CYCLE)')
    text = text.replace('G_RM_FOG_SHADE_A, G_RM_AA_ZB_OPA_SURF2', 'G_RM_AA_ZB_OPA_SURF, G_RM_AA_ZB_OPA_SURF2')
    text = text.replace('G_RM_FOG_SHADE_A, G_RM_AA_ZB_XLU_SURF2', 'G_RM_AA_ZB_XLU_SURF, G_RM_AA_ZB_XLU_SURF2')
    text = text.replace('G_RM_FOG_SHADE_A, G_RM_AA_ZB_TEX_EDGE2', 'G_RM_AA_ZB_TEX_EDGE, G_RM_AA_ZB_TEX_EDGE2')
    text = text.replace('G_RM_FOG_SHADE_A, G_RM_AA_ZB_DEC_LINE2', 'G_RM_AA_ZB_DEC_LINE, G_RM_AA_ZB_DEC_LINE2')
    text = text.replace('G_RM_FOG_SHADE_A, G_RM_AA_ZB_XLU_DECAL2', 'G_RM_AA_ZB_XLU_DECAL, G_RM_AA_ZB_XLU_DECAL2')
    text = text.replace('const Texture ', 'const u8 ')  # (sm64ex has no Texture type)
    text = re.sub(r'\bhood_', 'sg_', text)
    return text
body = '\n\n'.join(fix(defs[n]) for n in order if n in need)
if 'FOG' in body: print('WARNING: fog left:', set(re.findall(r'\w*FOG\w*', body)))
hdr = '// Generated by tools/shotgun_extract.py from Shoggoth World (levels/hood, courses/hd) - do not edit.\n' \
      '// The shotgun, its effect textures, the hood gangsters and their bullets.\n'
open(os.path.join(OUT, 'models.inc.c'), 'w').write(hdr + body + '\n')
# the roots are global (studio/shotgun.c, shotgun_objects.c use them)
decl = {'Gfx': 'Gfx', 'GeoLayout': 'GeoLayout', 'Texture': 'u8'}
h = ['// Generated by tools/shotgun_extract.py - do not edit.', '#ifndef STUDIO_SHOTGUN_MODELS_H', '#define STUDIO_SHOTGUN_MODELS_H']
for r in roots:
    kind = re.match(r'(?:ALIGNED8 )?(?:static )?const (\w+)', defs[r]).group(1)
    h.append('extern const %s %s[];' % (decl.get(kind, kind), re.sub(r'^hood_', 'sg_', r)))
h.append('#endif')
open(os.path.join(OUT, 'models.h'), 'w').write('\n'.join(h) + '\n')
print(len(need), 'definitions,', len(body), 'bytes')
